-- Astra schema. All times are timestamptz (UTC). Doses in µSv.

CREATE TABLE crew (
    id                    VARCHAR(16)  PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    role                  VARCHAR(50)  NOT NULL,
    skills                VARCHAR(255) NOT NULL DEFAULT '',   -- comma-separated, e.g. 'EVA,MEDIC'
    dose_budget_micro_sv  BIGINT       NOT NULL               -- mission dose budget
);

-- High volume: SEQUENCE ids (allocation 50) so Hibernate can batch inserts.
CREATE SEQUENCE telemetry_seq INCREMENT BY 50;
CREATE TABLE telemetry_reading (
    id           BIGINT           PRIMARY KEY,
    crew_id      VARCHAR(16)      NOT NULL REFERENCES crew(id),
    recorded_at  TIMESTAMPTZ      NOT NULL,
    metric       VARCHAR(32)      NOT NULL,
    value        DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_telemetry_crew_metric_time ON telemetry_reading (crew_id, metric, recorded_at);

CREATE SEQUENCE environment_seq INCREMENT BY 50;
CREATE TABLE environment_reading (
    id           BIGINT           PRIMARY KEY,
    module       VARCHAR(32)      NOT NULL,
    recorded_at  TIMESTAMPTZ      NOT NULL,
    metric       VARCHAR(32)      NOT NULL,
    value        DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_environment_module_metric_time ON environment_reading (module, metric, recorded_at);

CREATE TABLE checkin (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id           VARCHAR(16)  NOT NULL REFERENCES crew(id),
    recorded_at       TIMESTAMPTZ  NOT NULL,
    wellbeing         INTEGER      NOT NULL,
    mood              INTEGER      NOT NULL,
    stress            INTEGER      NOT NULL,
    symptoms          VARCHAR(500) NOT NULL DEFAULT '',        -- comma-separated
    reaction_mean_ms  INTEGER,
    reaction_lapses   INTEGER
);
CREATE INDEX idx_checkin_crew_time ON checkin (crew_id, recorded_at);

CREATE TABLE space_weather_event (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                  VARCHAR(16)      NOT NULL,
    onset                 TIMESTAMPTZ      NOT NULL,
    peak                  TIMESTAMPTZ      NOT NULL,
    peak_proton_flux_pfu  DOUBLE PRECISION NOT NULL,
    duration_hours        INTEGER          NOT NULL,
    received_at           TIMESTAMPTZ      NOT NULL
);

CREATE TABLE mission_task (
    id              VARCHAR(16)  PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    type            VARCHAR(16)  NOT NULL,                     -- EVA, INTERNAL, EXERCISE, SLEEP
    duration_hours  INTEGER      NOT NULL,
    required_skill  VARCHAR(32),                               -- null = anyone
    mandatory       BOOLEAN      NOT NULL,
    earliest_start  TIMESTAMPTZ  NOT NULL,
    latest_end      TIMESTAMPTZ  NOT NULL
);

CREATE TABLE schedule_entry (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id   VARCHAR(16) NOT NULL UNIQUE REFERENCES mission_task(id),  -- one assignment per task
    crew_id   VARCHAR(16) NOT NULL REFERENCES crew(id),
    start_at  TIMESTAMPTZ NOT NULL,
    end_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_schedule_crew_time ON schedule_entry (crew_id, start_at);

CREATE TABLE alert (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id       VARCHAR(16) REFERENCES crew(id),             -- null = mission-wide
    severity      VARCHAR(16)  NOT NULL,
    type          VARCHAR(32)  NOT NULL,
    message       VARCHAR(500) NOT NULL,
    evidence      JSONB,
    created_at    TIMESTAMPTZ  NOT NULL,
    acknowledged  BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_alert_created ON alert (created_at DESC);

CREATE TABLE replan_run (
    id                  VARCHAR(32)  PRIMARY KEY,
    created_at          TIMESTAMPTZ  NOT NULL,
    reason              VARCHAR(255),
    horizon_start       TIMESTAMPTZ  NOT NULL,
    horizon_hours       INTEGER      NOT NULL,
    seed                BIGINT       NOT NULL,
    response            JSONB        NOT NULL,                 -- full ReplanResponse, needed for /accept
    accepted_option_id  VARCHAR(32),
    accepted_at         TIMESTAMPTZ
);
